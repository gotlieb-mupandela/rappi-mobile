/**
 * Reads data/namespaced-feed-targets.json and writes
 * src/lib/storefront/namespacedTargets.generated.ts.
 *
 * The JSON is the namespacedFeedTargets() map from rappi-webapp
 * lib/mobile-feed-targets.ts at 7700b1d9ce42c15eda95da89e5d73445beea6852.
 * Each row is { id, href }. The id is hub--leaf. The href is the site path.
 * Labels are not part of this list.
 * Row order is the web function order, so a repeat run writes the same text.
 *
 * npm run gen:namespaced-targets
 * npm run check:namespaced-targets
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const NAMESPACED_SOURCE_SHA = '7700b1d9ce42c15eda95da89e5d73445beea6852';

const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const NAMESPACED_ID = /^[a-z0-9]+(?:-[a-z0-9]+)*--[a-z0-9]+(?:-[a-z0-9]+)*$/;
const AUDIENCE = new Set(['men', 'women', 'kids']);

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const NAMESPACED_JSON_PATH = path.join(ROOT, 'data', 'namespaced-feed-targets.json');
export const NAMESPACED_GENERATED_PATH = path.join(ROOT, 'src', 'lib', 'storefront', 'namespacedTargets.generated.ts');

function fail(index, message) {
  throw new Error(`namespaced target row ${index}: ${message}`);
}

/**
 * @param {unknown} rows
 * @returns {string}
 */
export function renderNamespacedTargets(rows) {
  if (!Array.isArray(rows)) throw new Error('namespaced feed targets must be a JSON array');
  const seenIds = new Set();
  const seenHrefs = new Set();
  const lines = [];
  rows.forEach((row, index) => {
    if (row === null || typeof row !== 'object' || Array.isArray(row)) fail(index, 'must be an object');
    const keys = Object.keys(row);
    for (const key of keys) {
      if (key !== 'id' && key !== 'href') fail(index, `unexpected key ${key}`);
    }
    if (typeof row.id !== 'string' || !NAMESPACED_ID.test(row.id)) fail(index, 'id must be hub--leaf');
    if (typeof row.href !== 'string') fail(index, 'href must be a string');
    const [hub, leaf] = row.id.split('--');
    if (!SLUG.test(hub) || !SLUG.test(leaf)) fail(index, 'hub and leaf must be lowercase slugs');
    let route;
    if (AUDIENCE.has(leaf)) {
      const href = `/shop/${hub}?audience=${leaf}`;
      if (row.href !== href) fail(index, `href must be ${href}`);
      route = `{ screen: "group", cat: ${JSON.stringify(hub)}, group: "all", audience: ${JSON.stringify(leaf)}, leaf: true }`;
    } else {
      const href = `/shop/${hub}?group=${encodeURIComponent(leaf)}`;
      if (row.href !== href) fail(index, `href must be ${href}`);
      route = `{ screen: "group", cat: ${JSON.stringify(hub)}, group: ${JSON.stringify(leaf)}, leaf: true }`;
    }
    if (seenIds.has(row.id)) fail(index, `duplicate id ${row.id}`);
    if (seenHrefs.has(row.href)) fail(index, `duplicate href ${row.href}`);
    seenIds.add(row.id);
    seenHrefs.add(row.href);
    lines.push(`  [${JSON.stringify(row.href)}, ${route}],`);
  });

  return `/**
 * GENERATED by scripts/gen-namespaced-targets.mjs. Do not edit by hand.
 * Source: rappi-webapp lib/mobile-feed-targets.ts namespacedFeedTargets at ${NAMESPACED_SOURCE_SHA}.
 * Keys are the exact href strings. Values are fixed group routes.
 * Look up with Map.get. The hub--leaf id is not a lookup key.
 * Row order follows the source file.
 */
import type { StorefrontRoute } from "./types.ts";

export const NAMESPACED_TARGETS: ReadonlyMap<string, StorefrontRoute> = new Map<string, StorefrontRoute>([
${lines.join('\n')}
]);
`;
}

/** Text of the committed data/namespaced-feed-targets.json. */
export function readCommittedNamespacedJson() {
  return execFileSync('git', ['show', 'HEAD:data/namespaced-feed-targets.json'], {
    cwd: ROOT,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
}

export function committedNamespacedJsonAvailable() {
  try {
    execFileSync('git', ['cat-file', '-e', 'HEAD:data/namespaced-feed-targets.json'], {
      cwd: ROOT,
      stdio: ['ignore', 'ignore', 'ignore'],
    });
    return true;
  } catch {
    return false;
  }
}

/**
 * @param {string} workingJson
 * @param {string | null} committedJson
 * @param {string} generatedText
 * @returns {string | null}
 */
export function namespacedCheckFailure(workingJson, committedJson, generatedText) {
  if (committedJson !== null && workingJson !== committedJson) {
    return `data/namespaced-feed-targets.json has drifted from the committed copy (rappi-webapp ${NAMESPACED_SOURCE_SHA}).`;
  }
  let rendered;
  try {
    rendered = renderNamespacedTargets(JSON.parse(committedJson ?? workingJson));
  } catch (error) {
    return error instanceof Error ? error.message : String(error);
  }
  if (generatedText !== rendered) {
    return 'namespacedTargets.generated.ts does not match the committed namespaced target list. Run npm run gen:namespaced-targets.';
  }
  return null;
}

function main() {
  const check = process.argv.includes('--check');
  const workingJson = readFileSync(NAMESPACED_JSON_PATH, 'utf8');
  if (check) {
    const committed = committedNamespacedJsonAvailable() ? readCommittedNamespacedJson() : null;
    const generated = readFileSync(NAMESPACED_GENERATED_PATH, 'utf8');
    const failure = namespacedCheckFailure(workingJson, committed, generated);
    if (failure) {
      process.stderr.write(`${failure}\n`);
      process.exit(1);
    }
    return;
  }
  writeFileSync(NAMESPACED_GENERATED_PATH, renderNamespacedTargets(JSON.parse(workingJson)));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
