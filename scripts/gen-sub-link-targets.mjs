/**
 * Reads data/storefront-sub-links.json and writes
 * src/lib/storefront/subLinkTargets.generated.ts.
 *
 * The JSON is a copy of rappi-webapp data/storefront-sub-links.json at
 * 1e8326d3406fccd6a4c997622da9507b5ab2b347.
 *
 * Keys in the generated table are the exact href strings. Values are fixed
 * group routes. The script does not copy label or count into app source.
 * Row order in the source file is kept, so a repeat run writes the same text.
 *
 * npm run gen:sub-links
 * npm run check:sub-links
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const SUB_LINK_SOURCE_SHA = '1e8326d3406fccd6a4c997622da9507b5ab2b347';

const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const REQUIRED_KEYS = ['hub', 'sub', 'label', 'href', 'count'];

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const SUB_LINK_JSON_PATH = path.join(ROOT, 'data', 'storefront-sub-links.json');
export const SUB_LINK_GENERATED_PATH = path.join(ROOT, 'src', 'lib', 'storefront', 'subLinkTargets.generated.ts');

function fail(index, message) {
  throw new Error(`sub-link row ${index}: ${message}`);
}

function slug(index, field, value) {
  if (typeof value !== 'string' || !SLUG.test(value)) {
    fail(index, `${field} must be a lowercase slug`);
  }
  return value;
}

/**
 * @param {unknown} rows
 * @returns {string}
 */
export function renderSubLinkTargets(rows) {
  if (!Array.isArray(rows)) throw new Error('storefront sub-links must be a JSON array');
  const seen = new Set();
  const lines = [];
  rows.forEach((row, index) => {
    if (row === null || typeof row !== 'object' || Array.isArray(row)) fail(index, 'must be an object');
    const keys = Object.keys(row);
    for (const key of keys) {
      if (key !== 'group' && !REQUIRED_KEYS.includes(key)) fail(index, `unexpected key ${key}`);
    }
    for (const key of REQUIRED_KEYS) {
      if (!Object.prototype.hasOwnProperty.call(row, key)) fail(index, `missing ${key}`);
    }
    const hub = slug(index, 'hub', row.hub);
    const sub = slug(index, 'sub', row.sub);
    let group;
    if (Object.prototype.hasOwnProperty.call(row, 'group') && row.group !== null) {
      group = slug(index, 'group', row.group);
    }
    if (typeof row.label !== 'string' || row.label.length === 0) fail(index, 'label must be a non-empty string');
    if (typeof row.href !== 'string') fail(index, 'href must be a string');
    if (!Number.isInteger(row.count) || row.count < 0) fail(index, 'count must be a non-negative integer');
    const href = group ? `/shop/${hub}?sub=${sub}&group=${group}` : `/shop/${hub}?sub=${sub}`;
    if (row.href !== href) fail(index, `href must be ${href}`);
    if (seen.has(href)) fail(index, `duplicate href ${href}`);
    seen.add(href);
    const folder = group ? `sub:${sub}@${group}` : `sub:${sub}`;
    const route = `{ screen: "group", cat: ${JSON.stringify(hub)}, group: ${JSON.stringify(folder)}, leaf: true }`;
    lines.push(`  ${JSON.stringify(href)}: ${route},`);
  });

  return `/**
 * GENERATED by scripts/gen-sub-link-targets.mjs. Do not edit by hand.
 * Source: rappi-webapp data/storefront-sub-links.json at ${SUB_LINK_SOURCE_SHA}.
 * Each key is an exact href. Each value is a fixed group route.
 * Labels and counts are not included. Row order follows the source file.
 */
import type { StorefrontRoute } from "./types.ts";

export const SUB_LINK_TARGETS: Readonly<Record<string, StorefrontRoute>> = {
${lines.join('\n')}
};
`;
}

function main() {
  const check = process.argv.includes('--check');
  const rows = JSON.parse(readFileSync(SUB_LINK_JSON_PATH, 'utf8'));
  const text = renderSubLinkTargets(rows);
  if (check) {
    const current = existsSync(SUB_LINK_GENERATED_PATH) ? readFileSync(SUB_LINK_GENERATED_PATH, 'utf8') : '';
    if (current !== text) {
      process.stderr.write('subLinkTargets.generated.ts does not match the generator. Run npm run gen:sub-links.\n');
      process.exit(1);
    }
    return;
  }
  writeFileSync(SUB_LINK_GENERATED_PATH, text);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
